"""Measure the low-pass LAME (via FFmpeg's libmp3lame) applies at each CBR bitrate.

Ground for the D4 fallback model: FFmpeg's MP3 muxer writes 0 in the LAME-tag lowpass
byte, so the encoder low-pass must be inferred from the bitrate. This script encodes
broadband noise at every tested bitrate, mono and stereo, decodes it and measures the
-6 dB band limit with SonicTrace's own detector. Results go to
research/lame_lowpass_verification.md and, as the model D4 loads, to
src/sonictrace/data/lame_cbr_cutoffs.json.

    python scripts/verify_lame_lowpass.py
"""

from __future__ import annotations

import json
import tempfile
from pathlib import Path

import numpy as np
import soundfile as sf

from sonictrace.analysis.spectral_analysis import compute_ltas, detect_bandlimit
from sonictrace.parsers.codec_inspector import inspect_mp3
from sonictrace.utils.tools import run_tool, tool_version

SAMPLE_RATES = [44100, 48000]
BITRATES = [32, 40, 48, 56, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320]  # all MPEG-1 Layer III CBR rates
ROOT = Path(__file__).resolve().parents[1]


def measure(sr: int, br: int, channels: int, tmp: Path) -> dict:
    rng = np.random.default_rng([br, channels])
    x = rng.normal(0, 0.1, (4 * sr, channels))
    wav, mp3, dec = tmp / "in.wav", tmp / "out.mp3", tmp / "dec.wav"
    sf.write(str(wav), x, sr, subtype="PCM_16")
    r = run_tool(["ffmpeg", "-nostdin", "-v", "error", "-y", "-i", str(wav), "-codec:a", "libmp3lame", "-b:a", f"{br}k", str(mp3)])
    assert r.returncode == 0, r.stderr
    tag = inspect_mp3(mp3).details.get("vbr_header") or {}
    r = run_tool(["ffmpeg", "-nostdin", "-v", "error", "-y", "-i", str(mp3), "-c:a", "pcm_f32le", str(dec)])
    assert r.returncode == 0, r.stderr
    y, _ = sf.read(str(dec), always_2d=True)
    f, p = compute_ltas(y[:, 0], sr)
    bl = detect_bandlimit(f, p, sr)
    return {"sample_rate": sr, "bitrate": br, "channels": channels, "tag_encoder": tag.get("encoder"),
            "tag_lowpass_hz": tag.get("lowpass_hz"), "measured_cutoff_hz": bl.cutoff_hz if bl.found else None,
            "steep": bl.steep, "reason": bl.reason}


def main() -> None:
    rows = []
    with tempfile.TemporaryDirectory(prefix="sonictrace_lame_") as t:
        for sr in SAMPLE_RATES:
            for ch in (1, 2):
                for br in BITRATES:
                    rows.append(measure(sr, br, ch, Path(t)))
                    print(rows[-1], flush=True)
    lines = ["# LAME low-pass vs. CBR bitrate (measured)", "",
             f"Encoder: libmp3lame via {tool_version('ffmpeg')}; 4 s Gaussian noise (-20 dBFS RMS);",
             "cutoff = SonicTrace -6 dB band-limit point of the decoded LTAS (channel 0). Generated by",
             "`python scripts/verify_lame_lowpass.py`. These values are the D4 fallback model",
             "(`src/sonictrace/analysis/codec_models.py`).", "",
             "| Sample rate | Channels | Bitrate (kbit/s) | LAME-tag encoder | LAME-tag lowpass | Measured cutoff (Hz) | Steep |",
             "|---|---|---|---|---|---|---|"]
    for r in rows:
        cut = f"{r['measured_cutoff_hz']:.0f}" if r["measured_cutoff_hz"] else f"none ({r['reason']})"
        lines.append(f"| {r['sample_rate']} | {'mono' if r['channels'] == 1 else 'stereo'} | {r['bitrate']} | "
                     f"{r['tag_encoder']} | {r['tag_lowpass_hz']} | {cut} | {r['steep']} |")
    out = ROOT / "research" / "lame_lowpass_verification.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    model = {
        "description": "Measured -6 dB cutoff of libmp3lame CBR encodes (broadband noise); used by test D4 when the "
                       "LAME tag records no low-pass. Entries whose drop was not steep are unusable (steep=false).",
        "encoder": "libmp3lame", "ffmpeg": tool_version("ffmpeg"), "generated_by": "scripts/verify_lame_lowpass.py",
        "entries": [{"sample_rate": r["sample_rate"], "channels": r["channels"], "bitrate_kbps": r["bitrate"],
                     "cutoff_hz": round(r["measured_cutoff_hz"], 1) if r["measured_cutoff_hz"] else None,
                     "steep": bool(r["steep"])} for r in rows],
    }
    data = ROOT / "src" / "sonictrace" / "data" / "lame_cbr_cutoffs.json"
    data.parent.mkdir(parents=True, exist_ok=True)
    data.write_text(json.dumps(model, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {out} and {data}")


if __name__ == "__main__":
    main()
